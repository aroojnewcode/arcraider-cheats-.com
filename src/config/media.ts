/** Stable cover image for blog cards / posts from slug. */
export function arcRaiderCoverForSlug(slug: string): string {
  let hash = 0;
  for (let i = 0; i < slug.length; i++) {
    hash = (hash * 31 + slug.charCodeAt(i)) >>> 0;
  }
  const index = hash % ARC_RAIDERS_LOCAL_IMAGES.length;
  return ARC_RAIDERS_LOCAL_IMAGES[index]!;
}
